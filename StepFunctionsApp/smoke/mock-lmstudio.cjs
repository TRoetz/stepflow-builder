// Minimal OpenAI-compatible mock of LM Studio for smoke-testing the
// browser's local AI execution path. Returns:
//   - decision prompts     -> {"decision": true}
//   - form/flow designer   -> a canned valid AiFormPlan JSON (fenced)
//   - dynamic API builder  -> a canned valid eav op draft JSON (method taken from the prompt)
//   - other prompts        -> plain text
// Serves GET /api/v1/models and POST /v1/chat/completions with CORS.
const http = require('http');

// Canned AiFormPlan returned for the AI Form Builder smoke test. Fenced to
// exercise the fence-stripping path in extractFormPlanJson.
